import { useState } from "react";
import { useParams } from "react-router-dom";
import { getReceipt, voidPayment } from "../api/api";
import { useApi } from "../api/hooks";
import { LogoMark } from "../ui/art";
import { Icon } from "../ui/icons";
import { Button, Chip, ErrorBox, Field, Page, Sheet, Skeleton, useToast } from "../ui/kit";
import { useBack } from "../ui/back";
import { dateTime, inr } from "../ui/format";
import { makePdf, shareOrDownload, download } from "../ui/pdf";
import type { Receipt } from "../api/types";

function pdfFor(r: Receipt) {
  return makePdf([
    { text: "MatsyaSetu", size: 22, bold: true, gap: 4 }, { text: "Payment receipt", size: 12, gap: 22 },
    { text: `Receipt ${r.receiptNo}`, bold: true }, { text: `Date: ${dateTime(r.at)}`, gap: 16 },
    { text: `Customer: ${r.customerName}` }, { text: `Trip: ${r.tripCode} (${r.supplierName})`, gap: 16 },
    { text: `Type: ${r.kind === "ADVANCE" ? "Advance" : "Current payment"}` }, { text: `Method: ${r.method === "CASH" ? "Cash" : "Online"}` },
    { text: `Amount received: ${inr(r.amountReceived)}`, size: 14, bold: true, gap: 14 },
    { text: `Trip amount: ${inr(r.tripAmount)}` }, { text: `Paid so far: ${inr(r.paidSoFar)}` },
    { text: `Remaining for this trip: ${r.remainingForTrip === null ? "known after handover" : inr(Math.max(r.remainingForTrip, 0))}`, bold: true, gap: 24 },
    ...(r.voided ? [{ text: "THIS PAYMENT WAS CANCELLED", bold: true }] : []), { text: "Generated by MatsyaSetu (demo PDF)", size: 9 }
  ]);
}

export default function ReceiptPage() {
  const { id, tcId, paymentId } = useParams();
  const back = useBack(`/trips/${id}/customers/${tcId}/history`);
  const toast = useToast();
  const { data, error, reload } = useApi(() => getReceipt(Number(id), Number(tcId), Number(paymentId)), [paymentId]);
  const [cancel, setCancel] = useState(false);
  const [reason, setReason] = useState("");
  const [busy, setBusy] = useState(false);
  if (error) return <Page title="Receipt Preview" onBack={back}><ErrorBox message={error} onRetry={reload} /></Page>;
  if (!data) return <Page title="Receipt Preview" onBack={back}><Skeleton n={2} h={160} /></Page>;
  const r = data;
  async function share() {
    const res = await shareOrDownload(pdfFor(r), `${r.receiptNo}.pdf`, `Receipt ${r.receiptNo}`);
    if (res === "downloaded") toast({ msg: "Receipt downloaded" });
  }
  async function doCancel() {
    setBusy(true);
    try { await voidPayment(Number(id), Number(tcId), Number(paymentId), reason); setCancel(false); toast({ msg: "Payment cancelled. History is kept." }); } catch (e) { toast({ msg: e instanceof Error ? e.message : "Could not cancel", tone: "bad" }); } finally { setBusy(false); }
  }
  return (
    <Page title="Receipt Preview" onBack={back} right={<button className="icon-btn" onClick={share} aria-label="Share receipt"><Icon n="share" /></button>}>
      <article className="receipt">
        <div className="rc-head"><LogoMark size={34} /><div className="grow"><b className="rc-t">Receipt</b><span className="sub">Trip {r.tripCode}</span></div><Chip tone={r.voided ? "bad" : "ok"}>{r.voided ? "Cancelled" : "Paid"}</Chip></div>
        <div className="rc-body">
          <b>{r.customerName}</b><span className="sub">{dateTime(r.at)} · {r.receiptNo}</span>
          <dl className="kv big">
            <div><dt>Type</dt><dd>{r.kind === "ADVANCE" ? "Advance" : "Current payment"}</dd></div>
            <div><dt>Amount received</dt><dd className="num">{inr(r.amountReceived)}</dd></div>
            <div><dt>Method</dt><dd>{r.method === "CASH" ? "Cash" : "Online"}</dd></div>
            <div className="hl"><dt>Remaining for trip</dt><dd className="num">{r.remainingForTrip === null ? "After handover" : inr(Math.max(r.remainingForTrip, 0))}</dd></div>
          </dl>
        </div>
        <p className="rc-foot">Generated by MatsyaSetu</p>
      </article>
      <div className="stack">
        <Button block onClick={share}><Icon n="share" size={18} /> Share</Button>
        <Button block variant="outline" onClick={() => { download(pdfFor(r), `${r.receiptNo}.pdf`); toast({ msg: "Receipt downloaded" }); }}><Icon n="download" size={18} /> Download PDF</Button>
        {!r.voided && <Button block variant="danger" onClick={() => setCancel(true)}>Cancel this payment</Button>}
      </div>
      <Sheet open={cancel} onClose={() => setCancel(false)} title="Cancel payment">
        <p className="sub">The payment stays in history, marked as cancelled. The trip balance goes back up by {inr(r.amountReceived)}.</p>
        <Field label="Reason"><input className="input" value={reason} onChange={(e) => setReason(e.target.value)} placeholder="e.g. Entered twice" autoFocus /></Field>
        <Button block variant="danger" busy={busy} disabled={reason.trim().length < 3} onClick={doCancel}>Cancel payment</Button>
      </Sheet>
    </Page>
  );
}
